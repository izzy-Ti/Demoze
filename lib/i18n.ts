export const LOCALES = ["en", "am"] as const;
export type Locale = (typeof LOCALES)[number];
export const LOCALE_NAMES: Record<Locale, string> = { en: "English", am: "አማርኛ" };

function merge<T extends object>(base: T, override: DeepPartial<T> | undefined): T {
  if (!override) return base;
  const out = { ...base } as Record<string, unknown>;
  for (const [k, v] of Object.entries(override)) {
    const b = (base as Record<string, unknown>)[k];
    out[k] =
      v && typeof v === "object" && b && typeof b === "object"
        ? merge(b as object, v as DeepPartial<object>)
        : (v ?? b);
  }
  return out as T;
}

const dictionaries: Record<Locale, Dictionary> = {
  en,
  am: merge(en, am),
};

export function getDictionary(locale: Locale = "en"): Dictionary {
  return dictionaries[locale] ?? en;
}

/** Simple "{name}" interpolation. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export function isLocale(value: string | undefined): value is Locale {
  return !!value && (LOCALES as readonly string[]).includes(value);
}
